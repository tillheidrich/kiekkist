export const ASTRO_RANGE = '^7.0.0';
export const meta = { id: 'astro', tier: 1, status: 'ready', label: 'Astro (static, content collections)', versions: `astro ${ASTRO_RANGE} (Node >= 22.12), @astrojs/sitemap`, editable: 'No CMS: texts live in src/content/*.json and are changed by the agency or an agent. With --cms sveltia|decap|pages|keystatic the client edits the same files in a browser UI.' };

const containsSection = (n) => { let hit = false; (function w(x) { if (hit) return; if (x.kkSection) { hit = true; return; } (x.children || []).forEach(w); })(n); return hit; };
const braceSafe = (s) => s.replace(/\{/g, '&#123;').replace(/\}/g, '&#125;');
const tsKey = (k) => (/^[a-zA-Z_$][\w$]*$/.test(k) ? k : JSON.stringify(k));

function pageTemplate(ir, page, fix) {
  const used = new Set();
  const walkBody = (node) => node.children.map((c) => {
    if (c.type === 'el' && c.kkSection) { used.add(ir.sections[c.kkSection].component); return `<${ir.sections[c.kkSection].component} />`; }
    if (c.type === 'el' && containsSection(c)) return braceSafe(fix(c.openRaw)) + walkBody(c) + c.closeRaw;
    if (c.type === 'el' && /^(script|style)$/.test(c.tag)) return c.openRaw.replace(/>$/, ' is:inline>') + c.children.map((x) => x.raw).join('') + c.closeRaw;
    if (c.type === 'comment') return '';
    return braceSafe(fix(c.type === 'el' ? serializeEl(c) : c.raw));
  }).join('');
  return { body: walkBody(page.body), used };
}
import { serialize as serializeEl } from '../html.js';

function componentFile(ir, sec, mapUrl) {
  const fields = sec.props.map((p) => `  ${tsKey(p.key)}?: string | null;`).join('\n');
  const colls = sec.collections.map((c) => `const ${camelItems(c)} = (await getCollection(${JSON.stringify(c)})).map((e) => e.data).sort((a, b) => a.order - b.order);`);
  const imports = [sec.props.length && 'getEntry', colls.length && 'getCollection'].filter(Boolean);
  const tpl = renderAstro(sec.node, { mapUrl });
  return `---
// ${sec.component}: section "${sec.name}" from ${sec.pages.join(', ')}. Generated by kk export; texts live in src/content.
${imports.length ? `import { ${imports.join(', ')} } from 'astro:content';\n` : ''}export interface Props {
${fields || '  // no editable props: fixed markup'}
}
${sec.props.length ? `const entry = await getEntry('sections', ${JSON.stringify(sec.name)});\nconst p = { ...(entry?.data ?? {}), ...Astro.props } as Record<string, string | null | undefined>;\n` : ''}${colls.join('\n')}
---
${tpl}
`;
}

function cmsFiles(ir, cms, files, notes) {
  if (!cms || cms === 'none') return;
  const colls = Object.values(ir.collections);
  const label = (s) => s.replace(/[-_]+/g, ' ').replace(/^\w/, (c) => c.toUpperCase());
  if (cms === 'sveltia' || cms === 'decap') {
    const y = ['# Generated by kk export. Field labels are taken from the content keys; rename them for the client.', 'backend:', '  name: gitea  # TODO(owner): gitea (Forgejo/Gitea), github or gitlab', '  repo: OWNER/REPO  # TODO(owner)', '  branch: main', 'media_folder: public/assets/img', 'public_folder: /assets/img', 'collections:'];
    y.push('  - name: sections', '    label: Abschnitte', '    files:');
    for (const s of Object.values(ir.sections)) if (s.props.length) {
      y.push(`      - name: ${s.name}`, `        label: ${JSON.stringify(label(s.name))}`, `        file: src/content/sections/${s.name}.json`, '        fields:');
      for (const p of s.props) y.push(`          - { name: ${JSON.stringify(p.key)}, label: ${JSON.stringify(label(p.key))}, widget: ${p.kind === 'rich' ? 'text' : p.kind === 'image' && p.attr === 'src' ? 'image' : 'string'}, required: false }`);
    }
    for (const c of colls) {
      y.push(`  - name: ${c.name}`, `    label: ${JSON.stringify(label(c.name))}`, '    files:', `      - name: ${c.name}`, `        label: ${JSON.stringify(label(c.name))}`, `        file: src/content/${c.name}.json`, '        fields:', '          - name: items', '            label: Einträge', '            widget: list', '            fields:', '              - { name: id, label: ID, widget: string }', '              - { name: order, label: Reihenfolge, widget: number }');
      for (const f of c.fields) y.push(`              - { name: ${JSON.stringify(f.key)}, label: ${JSON.stringify(label(f.key))}, widget: ${f.kind === 'rich' ? 'text' : 'string'}, required: false }`);
    }
    files.set('public/admin/config.yml', y.join('\n') + '\n');
    files.set('public/admin/index.html', `<!doctype html>\n<html lang="de">\n<head>\n<meta charset="utf-8">\n<meta name="viewport" content="width=device-width, initial-scale=1">\n<title>Inhalte bearbeiten</title>\n<meta name="robots" content="noindex">\n</head>\n<body>\n<!-- TODO(owner): download the ${cms === 'sveltia' ? 'Sveltia CMS bundle (sveltia-cms.js)' : 'Decap CMS bundle (decap-cms.js)'} into public/admin/ and keep it there: loading it from a CDN would be a third-party request. -->\n<script src="/admin/${cms === 'sveltia' ? 'sveltia' : 'decap'}-cms.js"></script>\n</body>\n</html>\n`);
    notes.push(`--cms ${cms}: public/admin/config.yml maps every section and collection; collections are stored as {"items": [...]} for the CMS list widget: run the CMS against a copy first. Self-host the CMS script (no CDN).`);
  } else if (cms === 'pages') {
    const y = ['# Pages CMS (pagescms.org), generated by kk export', 'media: public/assets/img', 'content:'];
    for (const s of Object.values(ir.sections)) if (s.props.length) { y.push(`  - name: ${s.name}`, `    label: ${JSON.stringify(label(s.name))}`, '    type: file', `    path: src/content/sections/${s.name}.json`, '    format: json', '    fields:'); for (const p of s.props) y.push(`      - { name: ${JSON.stringify(p.key)}, type: ${p.kind === 'rich' ? 'rich-text' : 'string'} }`); }
    files.set('.pages.yml', y.join('\n') + '\n');
    notes.push('--cms pages: .pages.yml written. Pages CMS works with GitHub only (US provider): an informed choice, not the default.');
  } else if (cms === 'keystatic') {
    const singletons = Object.values(ir.sections).filter((s) => s.props.length).map((s) => `    ${JSON.stringify(s.name)}: singleton({ label: ${JSON.stringify(label(s.name))}, path: 'src/content/sections/${s.name}', format: { data: 'json' }, schema: { ${s.props.map((p) => `${tsKey(p.key)}: fields.text({ label: ${JSON.stringify(label(p.key))}${p.kind === 'rich' ? ', multiline: true' : ''} })`).join(', ')} } }),`);
    files.set('keystatic.config.ts', `// Generated by kk export. Keystatic local mode; GitHub mode is the only online mode.\nimport { config, fields, singleton } from '@keystatic/core';\nexport default config({\n  storage: { kind: 'local' },\n  singletons: {\n${singletons.join('\n')}\n  },\n});\n`);
    notes.push('--cms keystatic: keystatic.config.ts for the section texts (local mode); add @keystatic/core and @keystatic/astro to the project and configure collections if the client edits lists.');
  } else if (cms === 'directus' || cms === 'storyblok') {
    files.set(`CMS-${cms}.md`, `# ${cms === 'directus' ? 'Directus (self-hosted)' : 'Storyblok (EU region)'}\n\nThe content model to create in ${cms}: one singleton per section, one collection per list.\n\n${Object.values(ir.sections).filter((s) => s.props.length).map((s) => `- **${s.name}**: ${s.props.map((p) => p.key).join(', ')}`).join('\n')}\n\n${Object.values(ir.collections).map((c) => `- list **${c.name}**: ${c.fields.map((f) => f.key).join(', ')}`).join('\n')}\n\nThen replace the JSON imports in src/content.config.ts with a loader that reads from ${cms} (credentials from env vars ${cms === 'directus' ? 'DIRECTUS_URL, DIRECTUS_TOKEN' : 'STORYBLOK_TOKEN'}; never commit them).\n`);
    notes.push(`--cms ${cms}: CMS-${cms}.md describes the content model; the loader is not generated (needs the client's instance).`);
  } else notes.push(`unknown --cms "${cms}" ignored (none|sveltia|decap|pages|keystatic|directus|storyblok)`);
}

export async function exportTarget(ir, opts = {}) {
  const files = new Map(), notes = [];
  const mapUrl = urlMapper(ir, 'routes');
  const routes = { ...legalRoutes(ir, '/impressum/', '/datenschutz/'), home: '/' };
  const inline = needsInline(ir);
  const data = mapIR(ir, mapUrl, routes);
  const fix = (h) => legalLinks(mapUrlsInHtml(h, mapUrl), routes);
  const site = ir.site.url;
  const pkgName = ir.site.slug.replace(/[^a-z0-9-]/g, '-');
  files.set('package.json', JSON.stringify({ name: pkgName, type: 'module', version: '0.1.0', private: true, scripts: { dev: 'astro dev', check: 'astro check', build: 'astro build', preview: 'astro preview' }, dependencies: { astro: ASTRO_RANGE, '@astrojs/sitemap': '^3.6.0' }, devDependencies: { '@astrojs/check': '^0.9.0', typescript: '^5.9.0' }, engines: { node: '>=22.12' } }, null, 2) + '\n');
  files.set('astro.config.mjs', `// Generated by kk export.\nimport { defineConfig } from 'astro/config';\nimport sitemap from '@astrojs/sitemap';\n\nexport default defineConfig({\n${site ? `  site: ${JSON.stringify(site)},\n` : "  // TODO(owner): set the real domain, e.g. site: 'https://www.example.com' (or export with --site-url).\n  // Without it the build still works; canonical links and the sitemap are left out until it is set.\n  // site: 'https://www.example.com',\n"}  trailingSlash: 'always',\n  build: { format: 'directory', inlineStylesheets: 'never' },\n  integrations: [sitemap()],\n  compressHTML: false, // keep the theme's whitespace: inline links and spacing stay as designed\n${inline ? "  // CSP via hashes is off: the theme uses inline style attributes or inline scripts, which a hash-based policy blocks.\n  // public/_headers and public/.htaccess carry a CSP with style-src 'unsafe-inline' instead.\n" : "  security: { csp: true }, // hashes for inline scripts and styles; proves nothing third-party loads\n"}});\n`);
  files.set('tsconfig.json', JSON.stringify({ extends: 'astro/tsconfigs/strict', include: ['.astro/types.d.ts', '**/*'], exclude: ['dist'] }, null, 2) + '\n');
  files.set('.gitignore', 'node_modules/\ndist/\n.astro/\n');
  // styles, fonts, scripts and images unchanged, at the same paths as in the theme (public/), linked exactly as the theme's pages link them
  files.set('public/tokens.css', ir.tokens.css);
  for (const a of ir.assets) files.set('public/' + a.path, readBin(opts.themeDir, a.path));
  if (inline) { files.set('public/_headers', headersFile(ir)); files.set('public/.htaccess', htaccess(ir)); notes.push('the theme uses inline style attributes or inline scripts: Astro\'s hash-based CSP is off; public/_headers and public/.htaccess set a CSP with style-src \'unsafe-inline\''); }
  // content
  const collDefs = [];
  for (const [name, s] of Object.entries(ir.sections)) if (s.props.length) files.set(`src/content/sections/${name}.json`, JSON.stringify(data.sections[name], null, 2) + '\n');
  for (const c of Object.values(ir.collections)) {
    files.set(`src/content/${c.name}.json`, JSON.stringify(data.collections[c.name].items, null, 2) + '\n');
    collDefs.push(`  ${JSON.stringify(c.name)}: defineCollection({\n    loader: file('src/content/${c.name}.json'),\n    schema: z.object({ id: z.string(), order: z.number(), ${c.fields.map((f) => `${tsKey(f.key)}: z.string().nullable().optional()`).join(', ')} }),\n  }),`);
  }
  files.set('src/content.config.ts', `// Generated by kk export: one collection for section texts, one per repeated list.\nimport { defineCollection } from 'astro:content';\nimport { glob, file } from 'astro/loaders';\nimport { z } from 'astro/zod';\n\nexport const collections = {\n  sections: defineCollection({\n    loader: glob({ pattern: '*.json', base: './src/content/sections' }),\n    schema: z.record(z.string(), z.string().nullable()),\n  }),\n${collDefs.join('\n')}\n};\n`);
  // components
  for (const s of Object.values(ir.sections)) files.set(`src/components/${s.component}.astro`, componentFile(ir, s, mapUrl));
  // layout
  files.set('src/layouts/Base.astro', `---
// Base layout: <html lang>, meta, Open Graph, canonical, JSON-LD slot. Generated by kk export.
// Stylesheets, fonts and scripts are linked by each page through the "head" slot, exactly as in the theme (public/).
interface Props { title: string; description?: string; path?: string; bodyClass?: string; bodyId?: string; ogImage?: string; noindex?: boolean; hasIcon?: boolean }
const { title, description = '', path = Astro.url.pathname, bodyClass, bodyId, ogImage, noindex = false, hasIcon = false } = Astro.props;
const canonical = Astro.site ? new URL(path, Astro.site).href : undefined;
---
<!doctype html>
<html lang=${JSON.stringify(ir.site.lang)}>
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
{description && <meta name="description" content={description} />}
{canonical && <link rel="canonical" href={canonical} />}
{noindex && <meta name="robots" content="noindex" />}
<meta property="og:type" content="website">
<meta property="og:title" content={title}>
{description && <meta property="og:description" content={description} />}
{canonical && <meta property="og:url" content={canonical} />}
{ogImage && <meta property="og:image" content={ogImage} />}
<meta property="og:locale" content=${JSON.stringify(ogLocale(ir.site.lang))}>
{!hasIcon && <link rel="icon" href="/favicon.svg" type="image/svg+xml" />}
{Astro.site && <link rel="sitemap" href="/sitemap-index.xml" />}
<slot name="head" />
</head>
<body class={bodyClass} id={bodyId}>
<slot />
</body>
</html>
`);
  // pages
  const headSlot = (page) => { const h = [...headExtraBefore(page, mapUrl), ...(page.stylesheets || []).map((x) => `<link rel="stylesheet" href="${mapUrl(x, 'href')}">`), ...headExtraAfter(page, mapUrl)].join('\n'); return `<Fragment slot="head" set:html={${JSON.stringify(h)}} />`; };
  const bodyId = (page) => /\bid="([^"]*)"/.exec(page.bodyOpen || '')?.[1] || '';
  const baseAttrs = (page) => `${bodyClass(page) ? ` bodyClass=${JSON.stringify(bodyClass(page))}` : ''}${bodyId(page) ? ` bodyId=${JSON.stringify(bodyId(page))}` : ''}${page.hasIcon ? ' hasIcon' : ''}`;
  const pageAstro = (page, routePath, depth) => {
    const { body, used } = pageTemplate(ir, page, fix);
    const up = '../'.repeat(depth + 1);
    return `---\nimport Base from '${up}layouts/Base.astro';\n${[...used].map((c) => `import ${c} from '${up}components/${c}.astro';`).join('\n')}\n---\n<Base title=${JSON.stringify(pageTitle(ir, page))} description=${JSON.stringify(page.description)} path=${JSON.stringify(routePath)}${baseAttrs(page)}>\n${headSlot(page)}\n${body}\n</Base>\n`;
  };
  for (const page of ir.pages) files.set(page.slug === 'index' ? 'src/pages/index.astro' : `src/pages/${page.slug}.astro`, pageAstro(page, page.path, 0));
  const index = ir.pages[0];
  const header = index.sections.map((n) => ir.sections[n]).find((s) => s.kind === 'header');
  const footer = index.sections.map((n) => ir.sections[n]).find((s) => s.kind === 'footer');
  const stubAstro = (title, inner, path, noindex) => `---\nimport Base from '../layouts/Base.astro';\n${header ? `import ${header.component} from '../components/${header.component}.astro';\n` : ''}${footer ? `import ${footer.component} from '../components/${footer.component}.astro';\n` : ''}---\n<Base title=${JSON.stringify(`${title} · ${ir.site.name}`)} path=${JSON.stringify(path)}${noindex ? ' noindex' : ''}${baseAttrs(index)}>\n${headSlot(index)}\n${header ? `<${header.component} />\n` : ''}<main id="inhalt">\n${plainSection(path.replace(/\//g, '') || '404', inner)}\n</main>\n${footer ? `<${footer.component} />\n` : ''}</Base>\n`;
  for (const key of ['impressum', 'datenschutz']) if (routes[key] && !ir.pages.some((p) => p.slug === key)) {
    files.set(`src/pages/${key}.astro`, stubAstro(LEGAL_TEXT[key].title, `<h1>${LEGAL_TEXT[key].title}</h1>\n${LEGAL_TEXT[key].body}`, `/${key}/`));
    notes.push(`src/pages/${key}.astro is a stub with TODO(owner) markers; kk launch reports it until it is filled`);
  }
  if (!ir.pages.some((p) => p.slug === '404')) files.set('src/pages/404.astro', stubAstro('Seite nicht gefunden', notFoundBody('/'), '/404/', true));
  files.set('public/favicon.svg', faviconSvg(ir));
  files.set('public/robots.txt', robotsTxt(ir, '/sitemap-index.xml'));
  files.set('DESIGN.md', ir.design || '');
  files.set('AGENTS.md', agentsMd(ir));
  cmsFiles(ir, opts.cms, files, notes);
  if (!site) notes.push('no --site-url: astro.config.mjs has no site yet (TODO(owner) comment); the build works, canonical links and the sitemap appear once site is set');
  files.set('README.md', readmeAstro(ir, site));
  notes.push('images are served from public/assets/img as in the theme (same files, same srcset); switch to astro:assets <Picture> only if AVIF/WebP variants are wanted');
  notes.push(`og:image is not set: add a 1200x630 image and pass ogImage to <Base> (seo.og)`);
  // static preview from the same templates and data (used by the post-export check without --build)
  const preview = new Map();
  const pmap = urlMapper(ir, 'routes');
  for (const page of ir.pages) preview.set(page.slug === 'index' ? 'index.html' : `${page.slug}/index.html`, pageHtml(ir, page, renderBody(ir, page, pmap, routes, data), { mapUrl: pmap }));
  preview.set('tokens.css', ir.tokens.css);
  for (const a of ir.assets) preview.set(a.path, readBin(opts.themeDir, a.path));
  return { files, notes, postCheck: { buildCmd: 'npm install --no-audit --no-fund && npm run build', buildDir: 'dist', pages: ir.pages.filter((p) => p.slug !== '404').map((p) => p.path), sourcePages: ir.pages.filter((p) => p.slug !== '404').map((p) => p.file), preview: { files: preview, pages: ir.pages.filter((p) => p.slug !== '404').map((p) => p.path) } } };
}

