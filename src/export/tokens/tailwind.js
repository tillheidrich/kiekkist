// DTCG -> Tailwind CSS v4 `@theme` file. Default palette and fonts are reset first (no bg-blue-500 drift).
import { flatten, isTypography, roleOf, valueCss, dimensionCss, isAlias, aliasPath } from './flatten.js';

const kebab = (s) => String(s).replace(/[^a-zA-Z0-9]+/g, '-').replace(/^-|-$/g, '').toLowerCase();
/** Tailwind variable for an alias target (so aliases stay references inside @theme). */
function twName(path) {
  const p = path.split('.');
  if (p[0] === 'color') return '--color-' + kebab(p.slice(1).join('-'));
  if (p[0] === 'font') return '--font-' + kebab(p.slice(p[1] === 'family' ? 2 : 1).join('-'));
  if ((p[0] === 'dimension' && /^(space|spacing)$/.test(p[1])) || /^(space|spacing)$/.test(p[0])) return '--spacing-' + kebab(p.slice(p[0] === 'dimension' ? 2 : 1).join('-'));
  if ((p[0] === 'dimension' && /^(radius|rounded)$/.test(p[1])) || /^(radius|rounded)$/.test(p[0])) return '--radius-' + kebab(p.slice(p[0] === 'dimension' ? 2 : 1).join('-'));
  if (p[0] === 'shadow') return '--shadow-' + kebab(p.slice(1).join('-'));
  if (p[0] === 'motion' && p[1] === 'easing') return '--ease-' + kebab(p.slice(2).join('-'));
  if (p[0] === 'motion' && p[1] === 'duration') return '--duration-' + kebab(p.slice(2).join('-'));
  return '--' + kebab(p.join('-'));
}
const val = (v, type) => (isAlias(v) ? `var(${twName(aliasPath(v))})` : valueCss(v, type));

export function toTailwindTheme(dtcg) {
  const lines = ['/* Generated by kk export from tokens.json (Tailwind CSS v4). Do not edit by hand. */', '@theme {', '  --color-*: initial;', '  --font-*: initial;'];
  for (const t of flatten(dtcg)) {
    if (isTypography(t)) {
      const role = kebab(roleOf(t.path)), v = t.value;
      if (v.fontSize !== undefined) lines.push(`  --text-${role}: ${isAlias(v.fontSize) ? val(v.fontSize) : typeof v.fontSize === 'object' ? dimensionCss(v.fontSize) : v.fontSize};`);
      if (v.lineHeight !== undefined) lines.push(`  --text-${role}--line-height: ${val(v.lineHeight, 'number')};`);
      if (v.letterSpacing !== undefined) lines.push(`  --text-${role}--letter-spacing: ${typeof v.letterSpacing === 'object' && !isAlias(v.letterSpacing) ? dimensionCss(v.letterSpacing) : val(v.letterSpacing, 'dimension')};`);
      if (v.fontWeight !== undefined) lines.push(`  --text-${role}--font-weight: ${val(v.fontWeight, 'fontWeight')};`);
      continue;
    }
    lines.push(`  ${twName(t.path)}: ${val(t.value, t.type)};`);
  }
  lines.push('}', '');
  return lines.join('\n');
}
